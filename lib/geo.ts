/** Departamentos (solo nombres) para un ISO code (case-insensitive). Vacío si no hay catálogo. */
export function departmentsForIso(iso?: string | null): string[] {
  if (!iso) return []
  return (GEO_BY_ISO[iso.toUpperCase()] ?? []).map((d) => d.name)
}

/** Municipios de un departamento dentro de un país (por ISO). Vacío si no hay catálogo. */
export function municipalitiesForIso(
  iso?: string | null,
  departmentName?: string | null,
): string[] {
  if (!iso || !departmentName) return []
  const dept = (GEO_BY_ISO[iso.toUpperCase()] ?? []).find((d) => d.name === departmentName)
  return dept?.municipalities ?? []
}

/** ¿El país (por ISO) tiene catálogo de departamentos? */
export function hasDepartmentCatalog(iso?: string | null): boolean {
  if (!iso) return false
  return (GEO_BY_ISO[iso.toUpperCase()] ?? []).length > 0
}
